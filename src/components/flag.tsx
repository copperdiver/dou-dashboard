/**
 * Флаг страны.
 *
 * Векторные флаги из `flag-icons`, а не эмодзи: эмодзи-флаги рисует
 * платформа, и Windows выводит вместо них буквы кода — в русском списке
 * получалось «во Боливия», «нт Гаити», что читается как опечатка,
 * а не как флаг.
 *
 * Флаг — украшение и якорь для взгляда, смысл несёт название страны
 * рядом. Поэтому он скрыт от чтения с экрана: диктовать «флаг Гаити»
 * перед словом «Гаити» значит повторяться.
 */
export function Flag({ iso2, className = '' }: { iso2: string | null; className?: string }) {
  if (!iso2 || !/^[A-Za-z]{2}$/.test(iso2)) return null

  return (
    <span
      // Соотношение 4:3 задано самим пакетом; фиксируем только высоту,
      // чтобы флаг сел на строку рядом с текстом.
      className={`fi fi-${iso2.toLowerCase()} inline-block h-3 w-4 shrink-0 rounded-[2px] align-[-1px] ${className}`}
      aria-hidden="true"
    />
  )
}
