import { strict as assert } from 'node:assert'
import { describe, it } from 'node:test'
import { isEditionDayOver } from '../src/worker/pumps/enumerate'

/**
 * Пустой дневной индекс закрывает день навсегда, поэтому вопрос «кончился
 * ли этот день» решает, потеряем мы выпуск или дождёмся его. Считать
 * нужно по Сан-Паулу: при TZ=Europe/Moscow сервер переходит на новую дату
 * на шесть часов раньше Бразилии, и в это окно свежий день закрывался
 * как «выпуска не было» ещё до публикации.
 */
describe('isEditionDayOver', () => {
  it('день ещё идёт: полночь по Сан-Паулу, выпуска ждать весь день', () => {
    // 03:00 UTC = 00:00 в Сан-Паулу того же числа.
    assert.equal(isEditionDayOver('2026-07-31', new Date('2026-07-31T03:00:00Z')), false)
  })

  it('день ещё идёт: поздний вечер по Сан-Паулу', () => {
    // 02:00 UTC следующих суток = 23:00 в Сан-Паулу 31-го.
    assert.equal(isEditionDayOver('2026-07-31', new Date('2026-08-01T02:00:00Z')), false)
  })

  it('день кончился: в Сан-Паулу уже следующая дата', () => {
    // 04:00 UTC = 01:00 в Сан-Паулу 1 августа.
    assert.equal(isEditionDayOver('2026-07-31', new Date('2026-08-01T04:00:00Z')), true)
  })

  it('московская полночь не считается концом бразильского дня', () => {
    // 21:00 UTC = 00:00 в Москве 1 августа, но в Сан-Паулу ещё 18:00 31-го.
    // Ровно этот сдвиг и терял свежие выпуски.
    assert.equal(isEditionDayOver('2026-07-31', new Date('2026-07-31T21:00:00Z')), false)
  })

  it('давно прошедший день закрывается сразу', () => {
    assert.equal(isEditionDayOver('2025-01-15', new Date('2026-07-31T12:00:00Z')), true)
  })
})
